'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {randomBytes}=require('node:crypto');
const {identityFixture}=require('./identity-fixture');
const {createUsersRepository}=require('../../../platform/storage/src/users');
const {createSessions}=require('../../../platform/identity/src/sessions');
const {createCloudApi}=require('../../../services/cloud-api/src/server');
test('HTTP application decisions enforce authentication, CSRF, MFA, target binding and no legacy grant bypass',async t=>{
  const f=await identityFixture(t),users=createUsersRepository(f.pool),a=await f.verified('http_reviewer'),b=await f.verified('http_applicant'),c=await f.verified('no_request');
  await users.bootstrapAdmin({verifiedUserId:a.userId});
  const enrollment=await f.accounts.beginMfaSetup({userId:a.userId,password:f.password});
  const auth=require('otpauth').URI.parse(enrollment.uri);
  await f.mfa.confirmEnrollment({userId:a.userId,totp:auth.generate({timestamp:f.clock.value})});f.clock.value+=30000;
  const sessions=createSessions({pool:f.pool,csrfKey:randomBytes(32),clock:f.clock});
  const observer=await sessions.issue({userId:b.userId}),admin=await sessions.issue({userId:a.userId,mode:'admin',mfaVerifiedAt:f.clock.now()});
  const server=createCloudApi({...f,sessions,publicOrigin:'https://thirdhand.example.invalid'});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>new Promise(resolve=>{server.closeAllConnections();server.close(resolve);}));
  const url=`http://127.0.0.1:${server.address().port}`;
  const get=(path,s)=>fetch(url+path,{headers:s?{cookie:s.cookie.split(';')[0]}:{}});
  const post=(path,body,s,csrf=true)=>fetch(url+path,{method:'POST',headers:{'content-type':'application/json',origin:'https://thirdhand.example.invalid',cookie:s.cookie.split(';')[0],...(csrf?{'x-csrf-token':s.csrfToken}:{})},body:JSON.stringify(body)});
  assert.equal((await get('/api/v1/me/admin-application')).status,401);
  assert.equal((await get('/api/v1/admin/applications',observer)).status,403);
  assert.equal((await post('/api/v1/me/admin-application',{reason:'request'},observer,false)).status,403);
  assert.equal((await post('/api/v1/me/admin-application',{reason:'request',userId:a.userId},observer)).status,400);
  const applied=await post('/api/v1/me/admin-application',{reason:'Maintain lab'},observer);assert.equal(applied.status,201);
  const application=(await applied.json()).application;
  assert.equal(application.userId,b.userId);
  const path=`/api/v1/admin/applications/${application.id}/decision`;
  assert.equal((await post(path,{decision:'approved',reason:'test'},observer)).status,403);
  assert.equal((await post(path,{decision:'approved',reason:'test',password:'wrong'},admin)).status,401);
  assert.equal((await post(path,{decision:'approved',reason:'test',password:f.password},admin)).status,401);
  const proof=()=>({password:f.password,totp:auth.generate({timestamp:f.clock.value+=30000})});
  const bypass=await post(`/api/v1/admin/users/${c.userId}/role`,{role:'admin',expectedVersion:1,reason:'no request',...proof()},admin);
  assert.equal(bypass.status,409);assert.equal((await bypass.json()).error,'ADMIN_REQUEST_REQUIRED');
  const result=await post(path,{decision:'approved',reason:'Approved by another administrator',...proof()},admin);assert.equal(result.status,200);
  assert.equal((await get('/api/v1/session',observer)).status,401);
  assert.equal((await users.findById(b.userId)).role,'admin');
});
